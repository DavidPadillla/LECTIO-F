enum ExerciseKind { choice, trueFalse, order }

class ReadingExercise {
  const ReadingExercise(
    this.prompt,
    this.options,
    this.correct,
    this.explanation,
    this.evidence, {
    this.kind = ExerciseKind.choice,
  });
  final String prompt, explanation, evidence;
  final List<String> options;
  final int correct;
  final ExerciseKind kind;
}

class OfflineReading {
  const OfflineReading(
    this.id,
    this.title,
    this.topic,
    this.level,
    this.text,
    this.word,
    this.definition,
    this.example,
    this.factQuestion,
    this.factOptions,
    this.factExplanation,
    this.factEvidence,
    this.sequence,
  );
  final String id, title, topic, level, text, word, definition, example;
  final String factQuestion, factExplanation, factEvidence;
  final List<String> factOptions, sequence;

  int get minutes => (text.split(RegExp(r'\s+')).length / 150).ceil();
  List<ReadingExercise> get exercises => [
    ReadingExercise(
      factQuestion,
      factOptions,
      0,
      factExplanation,
      factEvidence,
    ),
    ReadingExercise(
      '«${id.endsWith('2') ? sequence.first : sequence.last}» sucede antes que «${id.endsWith('2') ? sequence.last : sequence.first}».',
      const ['Verdadero', 'Falso'],
      id.endsWith('2') ? 0 : 1,
      '${id.endsWith('2') ? 'Es verdadero' : 'Es falso'}. Primero: ${sequence.first}. Al final: ${sequence.last}.',
      text,
      kind: ExerciseKind.trueFalse,
    ),
    ReadingExercise(
      'Ordena los acontecimientos del texto.',
      sequence,
      0,
      'El orden es: ${sequence.join(' → ')}.',
      text,
      kind: ExerciseKind.order,
    ),
  ];
}

